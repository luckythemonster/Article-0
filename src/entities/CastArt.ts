/**
 * The cast, drawn rather than loaded.
 *
 * Rowan, the orderlies, the enforcers and the drones used to be 516 PNGs
 * generated by PixelLab — 2.5 MB of art, a generator under `tools/pixellab/`,
 * and a silhouette tracer whose output had to be regenerated whenever any of it
 * changed. All of that is gone. This module draws the same cast out of a handful
 * of shapes at boot instead, the way `Vent4Boss`, `BossCore`, `RoofRelay` and
 * `Sensor` have always drawn themselves.
 *
 * ### It generates textures, not sprites
 *
 * The obvious way to do procedural characters is to draw them every frame with a
 * `Graphics`. This doesn't: it renders each pose once into a texture under the
 * *same key the sprite sheets used*, so `Player`, `Enforcer`, `Drone` and
 * `Orderly` keep playing ordinary Phaser animations and none of their code
 * changes. That matters for more than tidiness — the player's stance machine is
 * driven by animation completion (`crouch-down` and `crouch-up` are one-shots
 * whose end is what settles the stance), so anything that replaced the clips
 * with a rotating single sprite would have had to reimplement that.
 *
 * The cost is 512 small textures built once at boot, which is cheaper than it
 * sounds beside the map bake's several thousand draws.
 *
 * ### The silhouette leads
 *
 * Every figure is drawn to fill its {@link Silhouette} box, so the shape on
 * screen and the shape that collides are the same shape by construction. The
 * boxes are the ones the old tracer measured, kept unchanged, so guard radii,
 * the player's body and every shadow are numerically identical to before.
 */

/** How a figure is posed for one frame of one animation. */
interface Pose {
  /** Position around the cycle, 0..1. Drives the walk stride and the idle bob. */
  phase: number;
  /** 0 standing, 1 fully crouched. Fractional during the lower/rise clips. */
  crouch: number;
  /** Stride reach, as a fraction of the silhouette's length. 0 when still. */
  stride: number;
}

/** A role's shapes and colours. */
interface CastRole {
  silhouette: Silhouette;
  /** Main body fill. */
  body: number;
  /** The head, and the shoulder line — a shade off the body so the two separate. */
  head: number;
  /** Highlight — visor, lens, insignia. Reads as the thing's "front". */
  accent: number;
  /** Outline and underside. */
  dark: number;
  /** Drones have a chassis and rotors where everyone else has a head and legs. */
  chassis?: boolean;
}

